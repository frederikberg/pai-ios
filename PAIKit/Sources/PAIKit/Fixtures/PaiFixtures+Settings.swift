        guard method == "GET" || method == "PATCH",
            let parsed = try? JSONSerialization.jsonObject(with: Data(document.utf8)) as? [String: Any]
        else { return nil }
        switch (method, path) {
        case ("GET", "/api/settings"): return Data(document.utf8)
        case ("PATCH", "/api/settings/person"):
            return try? JSONSerialization.data(withJSONObject: ["person": parsed["person"] ?? [:]])
        case ("PATCH", "/api/settings/instance"):
            return try? JSONSerialization.data(withJSONObject: ["instance": parsed["instance"] ?? [:]])
        default: return nil
        }
    }

